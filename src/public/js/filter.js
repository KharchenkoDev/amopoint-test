/*
 * Фильтрация полей по значению select[name="type_val"]
 *
 * Алгоритм: при изменении select скрываем все строки с полями, затем
 * находим элементы, чей атрибут name содержит выбранное значение как
 * подстроку ([name*="val"]), и показываем их родительский <p>.
 *
 * Почему jQuery-селектор [name*=val], а не альтернативы:
 *
 *   1. Ручной перебор ($.each / for..of querySelectorAll('[name]')) —
 *      явный цикл с str.includes() делает то же самое, но многословнее.
 *      Выбрали декларативный селектор: он короче и читаемее.
 *
 *   2. data-атрибуты + конфигурационный объект — можно было заранее
 *      прописать data-visible-for="1,2" на каждом поле и читать их.
 *      Плюс: явная конфигурация видимости. Минус: требует изменения HTML,
 *      которого у нас нет.
 *
 *   3. Сторонние библиотеки (Vue, React, Alpine.js) — избыточны для одного
 *      события на одной странице; jQuery уже подключён.
 *
 *   4. Vanilla JS (querySelectorAll + element.closest) — работал бы без
 *      jQuery, но раз библиотека уже загружена, использовать её уместно.
 */
(function ($) {
    $(function () {
        const $select = $('select[name="type_val"]');
        const $selectRow = $select.closest('p');

        function applyFilter() {
            const val = $select.val();

            // Скрываем все строки с полями, кроме строки с самим select
            $('p').not($selectRow).hide();

            // Показываем строки с полями, чьё name содержит выбранное значение
            $('[name*="' + val + '"]').not($select).closest('p').show();
        }

        $select.on('change', applyFilter);

        // Применяем сразу при загрузке страницы
        applyFilter();
    });
}(jQuery));
